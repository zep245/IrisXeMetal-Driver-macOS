#!/usr/bin/env python3
"""Generate IrisXe stub subclasses of Apple's abstract IOAcceleratorFamily2
classes from src/accel/apple/SUMMARY.txt ('pure' lines only: internal,
non-exported methods are left to the kext linker's vtable patching).

usage: gen_subclasses.py SUMMARY.txt OUT.hpp OUT.cpp OUT_vtcheck.inc
"""
import re, sys

# our class, Apple parent, Apple real size (bytes, measured on macOS 15 in v0.16.0)
CLASSES = [
    ('IrisXeEventMachine',   'IOAccelEventMachineFast2', 3376),
    ('IrisXeDisplayMachine', 'IOAccelDisplayMachine',     376),
    ('IrisXeGLContext',      'IOAccelGLContext2',        4664),
    ('IrisXe2DContext',      'IOAccel2DContext2',        4352),
    ('IrisXeSurface',        'IOAccelSurface',           4920),
    ('IrisXeVidMemory',      'IOAccelVidMemory',          272),
    # milestone 2a: Apple's IOAccelSysMemory can't be created directly (its
    # alloc returns NULL); Apple's paravirt GPU uses an empty subclass too.
    # Real size not measured yet: 1024 is more than enough padding.
    ('IrisXeSysMemory',      'IOAccelSysMemory',         1024),
    # milestone 2c: receives Metal command buffers; Apple's paravirt subclass
    # is 0x6d0 bytes with its own fields from 0x6a8, so 0x6d0 is enough.
    ('IrisXeCommandQueue',   'IOAccelCommandQueue',      0x6d0),
    # v0.21.2: Apple's base queue makes no segment list (parseSegmentList gives
    # NULL -> "Invalid Resource"); drivers must. Apple's paravirt one is 0xc8.
    ('IrisXeSegmentResourceList', 'IOAccelSegmentResourceList', 0x100),
    ('IrisXeMemoryMap',      'IOAccelMemoryMap',          280),
    ('IrisXeResource',       'IOAccelResource2',          384),
]

# extra overrides written by hand (declared here, defined in IrisXeAccelMachines.cpp)
EXTRA = {
    'IrisXeEventMachine':   [(37, 'init', 'IOGraphicsAccelerator2*, unsigned int, int')],
    'IrisXeDisplayMachine': [(268, 'init', 'IOGraphicsAccelerator2*'), (269, 'start', 'IOPCIDevice*')],
    'IrisXeCommandQueue':   [(321, 'processSegment',
                              'IOAccelSegmentResourceList*, IOAccelKernelCommand const*, IOAccelKernelCommand const*'),
                             (323, 'processSegmentKernelCommand',
                              'IOAccelSegmentResourceList*, IOAccelKernelCommand const*, IOAccelKernelCommand const*'),
                             (326, 'processCommandBuffer', 'unsigned int, unsigned int'),
                             (328, 'parseSegmentList', 'IOAccelShared2*, IOAccelSegmentResourceListHeader const*, IOAccelDeviceShmem*'),
                             (330, 'processKernelCommand', 'IOAccelKernelCommand const*, IOAccelKernelCommand const*')],
    # v0.21.4: keep a table of live memory maps, so a Metal command can find
    # the pages behind a GPU address and map them (Apple never committed them)
    'IrisXeMemoryMap':      [(37, 'init', 'IOGraphicsAccelerator2*, IOAccelTask*, IOAccelMemory*, unsigned int'),
                             (20, 'free', '', 'void')],
}
# required methods whose body is hand written (IrisXeAccelMachines.cpp), not generated
HAND = {
    ('IrisXeMemoryMap', 'commitIntoGPUPageTable'),
    ('IrisXeMemoryMap', 'releaseFromGPUPageTable'),
}
# generated stubs that must not return 0 (Apple's own versions return true)
RETURNS = {
    ('IrisXeEventMachine', 'completeBarrier'): '1',
    ('IrisXeDisplayMachine', 'displayModeWillChange'): '1',
    ('IrisXeDisplayMachine', 'displayModeDidChange'): '1',
    # milestone 2a (buffers): same answers as Apple's paravirtual GPU
    ('IrisXeMemoryMap', 'updateGPUPageTable'): '1',
    ('IrisXeVidMemory', 'allocPhysical'): '1',
}


def parse(path):
    pure, cur, nslots = {}, None, {}
    for line in open(path):
        m = re.match(r'^(\w+) : \w+\s+own slots \d+\.\.(\d+)', line)
        if m:
            cur = m.group(1); pure[cur] = []; nslots[cur] = int(m.group(2)) + 1; continue
        m = re.match(r'^\s+pure\s+(\d+) (?:[\w:]+::)?(\w+)\((.*)\)(\s*const)?$', line.rstrip())
        if m and cur:
            pure[cur].append((int(m.group(1)), m.group(2), m.group(3), bool(m.group(4))))
    return pure, nslots


def main():
    summary, hpp, cpp, inc = sys.argv[1:5]
    pure, nslots = parse(summary)
    H = ['// GENERATED by tools/accelgen/gen_subclasses.py - stub subclasses (milestone 1, steps 1b/1c)',
         '#pragma once']
    for _, parent, _ in CLASSES:
        H.append('#include "apple/%s.h"' % parent)
    C = ['// GENERATED by tools/accelgen/gen_subclasses.py', '#include "IrisXeAccelClasses.hpp"', '']
    V = []
    for ours, parent, size in CLASSES:
        H += ['', 'class %s : public %s {' % (ours, parent),
              '    OSDeclareDefaultStructors(%s)' % ours, 'public:']
        C.append('OSDefineMetaClassAndStructors(%s, %s)' % (ours, parent))
        for k, name, params, const in pure[parent]:
            args = [a.strip() for a in params.split(',')] if params.strip() else []
            H.append('    virtual IRISXE_SLOT_RET %s(%s)%s override;   // slot %d' % (name, params, ' const' if const else '', k))
            named = ', '.join('%s a%d' % (a, i) for i, a in enumerate(args))
            if (ours, name) not in HAND:
                C.append('IRISXE_SLOT_RET %s::%s(%s)%s { return %s; }' % (ours, name, named, ' const' if const else '',
                                                                     RETURNS.get((ours, name), '0')))
        for e in EXTRA.get(ours, []):
            k, name, params = e[:3]
            ret = e[3] if len(e) > 3 else 'IRISXE_SLOT_RET'
            H.append('    virtual %s %s(%s) override;   // slot %d (hand written)' % (ret, name, params, k))
        H += ['private:',
              '    // Apple\'s part of the object is %d bytes; we never touch it, this' % size,
              '    // padding only makes our allocation big enough (checked at run time).',
              '    UInt8 _apple[%d];' % size, '};']
        C.append('')
        over = [2, 3, 9] + [p[0] for p in pure[parent]] + [e[0] for e in EXTRA.get(ours, [])]
        V.append('{ "%s", "%s", _ZTV%d%s, _ZTV%d%s, %d, { %s } },' % (
            ours, parent, len(ours), ours, len(parent), parent, nslots[parent], ', '.join(map(str, sorted(over)))))
    ext = ['', '// vtable symbols (C names of the C++ vtables)']
    for ours, parent, _ in CLASSES:
        ext.append('extern "C" void *_ZTV%d%s[];' % (len(ours), ours))
        ext.append('extern "C" void *_ZTV%d%s[];' % (len(parent), parent))
    open(hpp, 'w').write('\n'.join(H) + '\n')
    open(cpp, 'w').write('\n'.join(C) + '\n')
    open(inc, 'w').write('// GENERATED: vtable check table for IrisXeAccelTest.cpp\n' + '\n'.join(ext) +
                         '\n#define IRISXE_VT_TABLE \\\n' + ' \\\n'.join(V) + '\n')
    print('generated %d classes' % len(CLASSES))


if __name__ == '__main__':
    main()
