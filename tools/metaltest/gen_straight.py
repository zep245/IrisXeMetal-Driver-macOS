#!/usr/bin/env python3
"""Writes big_straight.inc: 480 distinct statements on uint x, y (valid Metal
and C). Used by the big_straight kernel (kernels.metal) and its CPU reference
(irisxe-metaltest.m): compiled it is far over the 3968-byte inline kernel
limit, so it runs from its own GPU buffer. Rerun only to change it."""
import random
r = random.Random(7)
L = ['// generated by gen_straight.py - do not edit']
for i in range(480):
    k = r.randrange(1 << 31) | 1; c = r.randrange(1 << 32); s = r.randrange(1, 31)
    if i % 4 == 0:   L.append('x = x * %uu + (y ^ %uu);' % (k, c))
    elif i % 4 == 1: L.append('y = (y + x) ^ (x >> %d);' % s)
    elif i % 4 == 2: L.append('x = (x ^ %uu) + (y << %d);' % (c, s))
    else:            L.append('y = y * %uu - x;' % k)
open('big_straight.inc', 'w').write('\n'.join(L) + '\n')
